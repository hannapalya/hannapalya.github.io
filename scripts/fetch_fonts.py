#!/usr/bin/env python3
"""Download the site's web fonts (latin + latin-ext subsets) from Google Fonts into
assets/fonts/ and write assets/css/fonts.css. Re-run to update the fonts.

Files are named family-style-weight-subset.woff2. Quicksand is variable: one file per subset
covers weights 300 to 700 (the site uses 300 for the name and 400 for everything else)."""
import os, re, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSS_URL = "https://fonts.googleapis.com/css2?family=Quicksand:wght@300..700&display=swap"
UA = "Mozilla/5.0 (Macintosh; Intel Mac OS X 14_0) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0 Safari/537.36"
KEEP = {"latin", "latin-ext"}


def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    return urllib.request.urlopen(req, timeout=30).read()


def main():
    css = get(CSS_URL).decode()
    os.makedirs(os.path.join(ROOT, "assets", "fonts"), exist_ok=True)
    out = ["/* Quicksand (SIL Open Font License 1.1), self-hosted. "
           "Generated by scripts/fetch_fonts.py; do not edit. */"]
    saved = {}  # Google URL -> local file name
    for subset, block in re.findall(r"/\* ([a-z-]+) \*/\s*(@font-face\s*\{[^}]*\})", css):
        if subset not in KEEP:
            continue
        family = re.search(r"font-family: '([^']+)'", block).group(1)
        style = re.search(r"font-style: (\w+)", block).group(1)
        weight = re.search(r"font-weight: ([^;]+);", block).group(1).replace(" ", "-")
        url = re.search(r"url\((https://[^)]+\.woff2)\)", block).group(1)
        if url not in saved:
            saved[url] = f"{family.lower().replace(' ', '-')}-{style}-{weight}-{subset}.woff2"
            with open(os.path.join(ROOT, "assets", "fonts", saved[url]), "wb") as fh:
                fh.write(get(url))
        out.append(block.replace(url, f"/assets/fonts/{saved[url]}"))
    with open(os.path.join(ROOT, "assets", "css", "fonts.css"), "w") as fh:
        fh.write("\n".join(out) + "\n")
    print(f"wrote {len(out) - 1} @font-face rules, {len(saved)} font files")


if __name__ == "__main__":
    main()
