#!/usr/bin/env python3
"""Make the web-sized images from the originals in scripts/originals/.

  python3 scripts/make_images.py

  assets/img/hanna.jpg         square crop of the portrait, PORTRAIT_PX square: the home page's
                               JSON-LD Person image (the page itself shows no photo)
  assets/img/crochet/*.webp    crochet photos, longest side 1000px, transparency kept, and a
                               480px-wide copy of each (NAME-480.webp) for the gallery's srcset
  _data/crochet.yml            gallery rows (src, width, height, alt, caption)

To change the portrait, put the original in scripts/originals/, point PORTRAIT_SRC at it, add a
line to PORTRAIT_CROPS if the face is not in the middle, and re-run. Edit CROCHET below to change
captions or alt text, then re-run.
"""
import json, os
from PIL import Image, ImageOps

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ORIG = os.path.join(ROOT, "scripts", "originals")
PORTRAIT_SRC = "scripts/originals/hanna-photo.jpg"      # relative to the repo root
PORTRAIT_PX = 288                                       # the side of the square, in px
# Where to cut the square from each original, by file name: the side as a fraction of the shorter
# side, and the centre as fractions of the width and height. Unlisted originals are cut from the
# middle. Keep the face near the centre: sites that show the image may crop it to a circle.
PORTRAIT_CROPS = {
    "hanna-photo.jpg": (0.62, 0.50, 0.40),
}
CROCHET = [
    ("dino.png", "Dinosaur vest", "Crocheted pink vest with a maroon dinosaur on the front"),
    ("hat.png", "Bucket hat", "Crocheted cream bucket hat with blue, lilac and yellow granny squares"),
    ("scarf.png", "Scarf in progress", "A striped scarf in progress on a crochet hook, beside a bunch of pink flowers"),
]


def portrait():
    im = ImageOps.exif_transpose(Image.open(os.path.join(ROOT, PORTRAIT_SRC))).convert("RGB")
    W, H = im.size
    f, fx, fy = PORTRAIT_CROPS.get(os.path.basename(PORTRAIT_SRC), (1.0, 0.5, 0.5))
    side = int(min(W, H) * f)
    left = min(max(0, int(W * fx) - side // 2), W - side)    # keep the square inside the photo
    top = min(max(0, int(H * fy) - side // 2), H - side)
    im = im.crop((left, top, left + side, top + side)).resize((PORTRAIT_PX, PORTRAIT_PX), Image.LANCZOS)
    out = os.path.join(ROOT, "assets", "img", "hanna.jpg")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    im.save(out, quality=82, optimize=True, progressive=True)
    print(f"{out}: {os.path.getsize(out) // 1024} KB")


def crochet():
    os.makedirs(os.path.join(ROOT, "assets", "img", "crochet"), exist_ok=True)
    rows = []
    for name, caption, alt in CROCHET:
        im = ImageOps.exif_transpose(Image.open(os.path.join(ORIG, name))).convert("RGBA")
        im.thumbnail((1000, 1000), Image.LANCZOS)
        rel = f"assets/img/crochet/{os.path.splitext(name)[0]}.webp"
        im.save(os.path.join(ROOT, rel), "WEBP", quality=80, method=6)
        rows.append((rel, im.width, im.height, alt, caption))
        print(f"{rel}: {im.width}x{im.height}, {os.path.getsize(os.path.join(ROOT, rel)) // 1024} KB")
        small, rel_s = im.copy(), rel.replace(".webp", "-480.webp")   # the gallery shows them ~11rem wide
        small.thumbnail((480, 100000), Image.LANCZOS)
        small.save(os.path.join(ROOT, rel_s), "WEBP", quality=80, method=6)
        print(f"{rel_s}: {small.width}x{small.height}, {os.path.getsize(os.path.join(ROOT, rel_s)) // 1024} KB")
    with open(os.path.join(ROOT, "_data", "crochet.yml"), "w", encoding="utf-8") as fh:
        fh.write(crochet_yaml(rows))


def crochet_yaml(rows):
    """_data/crochet.yml for rows of (path, width, height, alt, caption). The text is written as JSON
    strings, which YAML reads as double-quoted scalars, so quotes and backslashes in it are safe."""
    q = lambda t: json.dumps(t, ensure_ascii=False)
    return "# Generated by scripts/make_images.py; edit captions and alt text there.\n" + "".join(
        f"- src: /{rel}\n  width: {w}\n  height: {h}\n  alt: {q(alt)}\n  caption: {q(cap)}\n"
        for rel, w, h, alt, cap in rows)


if __name__ == "__main__":
    os.makedirs(os.path.join(ROOT, "_data"), exist_ok=True)
    portrait()
    crochet()
